#'   \item{`default_date`}{Date of default.}
#'   \item{`ead`}{Exposure at default.}
#'   \item{`product`}{`"unsecured"`, `"mortgage"` or `"auto"`.}
#'   \item{`collateral_value`}{Collateral value at default; `0` when unsecured.}
#'   \item{`ltv`}{Loan-to-value at default; `0` when unsecured.}
#'   \item{`months_on_book`}{Months since origination at default.}
#'   \item{`prior_dpd_max`}{Worst days past due in the year before default (multiples of 30).}
#'   \item{`region`}{Region of the facility.}
#'   \item{`status`}{`"closed"`, `"cured"` or `"open"` at the observation date.}
#'   \item{`close_date`}{Date the workout closed or the cure was confirmed; `NA` when open.}
#' }
#' @source Synthetic. Generated by `data-raw/scr_demo_lgd.R`, seed `20260904`, in the package source
#'   repository <https://github.com/evandeilton/scorecraft>.
#' @family data
#' @examples
#' table(scr_demo_lgd$product, scr_demo_lgd$status)
