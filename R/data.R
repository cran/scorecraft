#' non-cures recover according to product-specific profiles until a close
#' date; events still running at the observation date are `open`, a few of
#' them older than the maximum recovery period. Thirty facilities default
#' twice after a cure, half of them within nine months, so that
#' [scr_workout()] merges the two spells into one event. Built for
#' [scr_workout()], [scr_lgd()] and the in-default examples.
#'
#' @format A `data.frame` with 900 rows and 12 columns:
#' \describe{
#'   \item{`default_id`}{Default event identifier.}
