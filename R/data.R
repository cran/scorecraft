#' Synthetic default events for the workout LGD examples
#'
#' 900 default events on three products (unsecured, mortgage, auto)
#' observed until 2026-06-30, with the drivers a workout LGD model reads:
#' collateral, loan-to-value, time on book, the worst delinquency before
